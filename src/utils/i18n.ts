/**
 * Whether a translation key exists in the requested locale (or in the English
 * fallback). Optional text — tool help metadata, for example — uses this so an
 * untranslated key falls back to the English source string instead of rendering
 * the raw key.
 */
export function hasTranslation(lang: string | undefined, key: string): boolean {
  const locale: Locale = lang === 'id' ? 'id' : 'en';
  return translations[locale][key] !== undefined || translations.en[key] !== undefined;
}

/**
 * Translate a key to the given locale, with optional variable interpolation.
 * Falls back to 'en' if the key is missing in the requested locale.
 * @param lang - Language code ('en' | 'id'). Defaults to 'en' for unknown values.
 * @param key  - Translation key (e.g. 'menu.greeting')
 * @param vars - Optional map of {variable} placeholders to replace in the string
 */
export function t(lang: string | undefined, key: string, vars: Record<string, string | number> = {}): string {
  const locale: Locale = lang === 'id' ? 'id' : 'en';
  let str = translations[locale][key] ?? translations.en[key];
  if (str === undefined) {
    logger.warn({ key, locale }, '[i18n] Missing translation key');
    str = key;
  }
  for (const [k, v] of Object.entries(vars)) {
    // A function replacer is required: with a string replacement, `$&`, `$` and
    // `$'` inside an interpolated value are expanded as substitution patterns,
    // so a value containing `$&` re-injected the matched placeholder
    // ('a$&b' became 'a{name}b'). Interpolated values can be user-controlled.
    str = str.replaceAll(`{${k}}`, () => String(v));
  }
  return str;
}
